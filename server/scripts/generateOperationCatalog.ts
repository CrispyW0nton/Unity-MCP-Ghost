#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createMcpServer } from "../src/mcp/createServer.js";
import { listOperationCatalog, OperationCatalogVersion } from "../src/mcp/operationCatalog.js";
import type { UnityClient } from "../src/unity/UnityClient.js";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const jsonPath = resolve(repositoryRoot, "docs/generated/operation-catalog.json");
const csharpPath = resolve(repositoryRoot, "Packages/com.crispywonton.unity-mcp-ghost/Editor/Bridge/GeneratedOperationCatalog.cs");

async function main(): Promise<void> {
  const unity = {
    endpoint: "ws://127.0.0.1:0/unity-mcp-ghost/",
    queueEndpoint: undefined,
    isConnected: async () => false,
    request: async () => ({ ok: true })
  } as unknown as UnityClient;
  const server = createMcpServer({ unity, toolProfiles: ["all"] });
  const operations = listOperationCatalog(server);
  const generatedAt = "generated-deterministically";
  const json = `${JSON.stringify({ catalogVersion: OperationCatalogVersion, generatedAt, operations }, null, 2)}\n`;
  const bridgeOperations = [...new Set(operations.flatMap((operation) => operation.bridgeOperations ?? []))].sort();
  const csharp = renderCsharp(bridgeOperations);

  if (process.argv.includes("--check")) {
    await assertCurrent(jsonPath, json);
    await assertCurrent(csharpPath, csharp);
    process.stdout.write(`Operation catalog is current (${operations.length} tools, ${bridgeOperations.length} direct bridge mappings).\n`);
    return;
  }

  await mkdir(dirname(jsonPath), { recursive: true });
  await writeFile(jsonPath, json, "utf8");
  await writeFile(csharpPath, csharp, "utf8");
  process.stdout.write(`Generated ${operations.length} tools and ${bridgeOperations.length} direct bridge mappings.\n`);
}

function renderCsharp(operations: string[]): string {
  const values = operations.map((operation) => `            "${operation}"`).join(",\n");
  return `// <auto-generated />
namespace CrispyWonton.UnityMcpGhost.Editor
{
    internal static class GeneratedOperationCatalog
    {
        internal const int Version = ${OperationCatalogVersion};

        internal static readonly string[] DirectBridgeOperations =
        {
${values}
        };
    }
}
`;
}

async function assertCurrent(path: string, expected: string): Promise<void> {
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch {
    throw new Error(`Generated operation catalog file is missing: ${path}`);
  }
  if (current.replace(/\r\n/g, "\n") !== expected.replace(/\r\n/g, "\n")) {
    throw new Error(`Generated operation catalog is stale: ${path}. Run npm run generate:catalog.`);
  }
}

await main();
