import { execFile, type ChildProcess } from "node:child_process";
import { platform } from "node:os";
import { promisify } from "node:util";

export const certifiedUnityVersion = "2022.3.62f1";

export function assertCertifiedUnityVersion(version: string): void {
  if (version.trim() !== certifiedUnityVersion) {
    throw new Error(`Unity version '${version.trim() || "unknown"}' is not the certified version ${certifiedUnityVersion}.`);
  }
}

export async function assertCertifiedUnityEditor(path: string): Promise<void> {
  const { stdout } = await promisify(execFile)(path, ["-version"], { windowsHide: true, timeout: 15000, maxBuffer: 4096 });
  assertCertifiedUnityVersion(stdout);
}

/** Stop only a child spawned by this runner, including its owned Windows helper processes. */
export async function stopOwnedProcess(
  child: ChildProcess,
  terminateTree: ((processId: number) => Promise<void>) | undefined = platform() === "win32" ? stopWindowsProcessTree : undefined
): Promise<void> {
  if (!child.pid || child.exitCode !== null || child.signalCode !== null) return;
  let resolveExit!: () => void;
  const exited = new Promise<void>((done) => {
    resolveExit = done;
  });
  child.once("exit", resolveExit);
  let treeFailure: unknown;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    if (terminateTree) {
      try {
        await terminateTree(child.pid);
      } catch (error) {
        treeFailure = error;
        if (child.exitCode === null && child.signalCode === null) {
          // A failed tree helper must not strand the owned root process. Still
          // report the tree failure: root exit does not prove descendant cleanup.
          child.kill("SIGKILL");
        }
      }
    } else {
      child.kill("SIGTERM");
    }
    await Promise.race([
      exited,
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => {
          child.kill("SIGKILL");
          reject(new Error(`Owned process ${child.pid} did not exit within the cleanup deadline.`));
        }, 10000);
      })
    ]);
    if (treeFailure) throw treeFailure;
  } finally {
    clearTimeout(timer);
    child.removeListener("exit", resolveExit);
  }
}

async function stopWindowsProcessTree(processId: number): Promise<void> {
  if (!Number.isSafeInteger(processId) || processId <= 0) throw new Error("Owned process ID must be a positive integer.");
  // taskkill /T can stall before terminating even a trivial process tree. The
  // Windows certification runners require PowerShell 7's native .NET tree kill;
  // no shell-interpolated command or process-name/global termination is used.
  const command = [
    '$ErrorActionPreference = "Stop"',
    "$ownedProcess = [System.Diagnostics.Process]::GetProcessById([int]$env:GHOST_TEST_OWNED_PROCESS_ID)",
    'try { $ownedProcess.Kill($true); if (-not $ownedProcess.WaitForExit(10000)) { throw "Owned process did not exit within the cleanup deadline." } } finally { $ownedProcess.Dispose() }'
  ].join("; ");
  await promisify(execFile)("pwsh.exe", ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command], {
    windowsHide: true,
    timeout: 15000,
    maxBuffer: 4096,
    env: { ...process.env, GHOST_TEST_OWNED_PROCESS_ID: String(processId) }
  });
}

/** Validate the NUnit aggregate generated by our owned Unity test run, not arbitrary XML. */
export function validateUnityTestResults(xml: string): { total: number; passed: number; failed: number; skipped: number; inconclusive: number } {
  const root = /<test-run\s+([^>]+)>/.exec(xml);
  if (!root || !xml.trimEnd().endsWith("</test-run>")) throw new Error("Unity test result is missing a complete test-run element.");
  const attributes = new Map<string, string>();
  for (const match of root[1].matchAll(/([\w-]+)="([^"]*)"/g)) {
    if (attributes.has(match[1])) throw new Error(`Unity test result has duplicate ${match[1]} attributes.`);
    attributes.set(match[1], match[2]);
  }
  const count = (name: string): number => {
    const value = attributes.get(name) ?? "";
    if (!/^\d+$/.test(value) || !Number.isSafeInteger(Number(value))) throw new Error(`Unity test result has an invalid ${name} count.`);
    return Number(value);
  };
  const result = { total: count("total"), passed: count("passed"), failed: count("failed"), skipped: count("skipped"), inconclusive: count("inconclusive") };
  if (attributes.get("result") !== "Passed" || result.total === 0 || result.passed !== result.total || result.failed || result.skipped || result.inconclusive) {
    throw new Error(`Unity test result is not completely green: ${JSON.stringify(result)}.`);
  }
  return result;
}

export function unityEditorPath(): string {
  return (
    process.env.UNITY_EDITOR_PATH ??
    (platform() === "win32"
      ? `C:\\Program Files\\Unity\\Hub\\Editor\\${certifiedUnityVersion}\\Editor\\Unity.exe`
      : platform() === "darwin"
        ? `/Applications/Unity/Hub/Editor/${certifiedUnityVersion}/Unity.app/Contents/MacOS/Unity`
        : "/opt/unity/Editor/Unity")
  );
}
